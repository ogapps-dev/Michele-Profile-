let likes = {};

function generateFeed() {
    const container = document.getElementById('feed-container');
    if (!container) return;

    for (let i = 1; i <= 20; i++) {
        const post = document.createElement('div');
        post.className = 'post';
        post.dataset.postId = i;
        post.style.animationDelay = `${i * 0.05}s`;
        
        const baseLikes = 3000 + (i * 500) + Math.floor(Math.random() * 500);
        likes[i] = baseLikes;
        
        post.innerHTML = `
            <div class="post-header">
                <img src="michele.jpg" alt="Michele" class="post-avatar" width="40" height="40" loading="${i > 3 ? 'lazy' : 'eager'}" decoding="async">
                <span class="post-user">michele_exclusive</span>
                <span class="post-time">${i}h ago</span>
            </div>
            <div class="post-image-container">
                <img src="model${i}.jpg" alt="Post ${i}" class="post-image" width="400" height="500" loading="lazy" decoding="async">
            </div>
            <div class="post-actions">
                <button class="like-btn" onclick="handleLike(${i}, this)">♡</button>
                <span class="like-count" id="likes-${i}">${formatNumber(baseLikes)}</span>
            </div>
            <div class="comments-section">
                <div class="comments-list" id="comments-${i}">${renderComments(i)}</div>
                <div class="comment-input-container">
                    <input type="text" class="comment-input" id="input-${i}" placeholder="Add comment..." onkeypress="handleEnter(event, ${i})">
                    <button class="comment-submit" onclick="submitComment(${i})">Post</button>
                </div>
            </div>
        `;
        
        container.appendChild(post);
    }
}

function renderComments(postId) {
    const comments = commentsData[postId] || [];
    return comments.map(c => `
        <div class="comment">
            <span class="comment-user">${c.user}</span>
            <span class="comment-text">${c.text}</span>
            <span style="color: rgba(255,255,255,0.5); font-size: 0.75rem; margin-left: 0.5rem;">${c.time}</span>
        </div>
    `).join('');
}

function formatNumber(num) {
    if (num >= 1000) return (num / 1000).toFixed(1) + 'K';
    return num;
}

function handleLike(postId, btn) {
    if (btn.classList.contains('liked')) return;
    btn.classList.add('liked');
    btn.innerHTML = '♥';
    likes[postId]++;
    document.getElementById(`likes-${postId}`).textContent = formatNumber(likes[postId]);
    createGoldEffect(btn);
}

function createGoldEffect(element) {
    const rect = element.getBoundingClientRect();
    const centerX = rect.left + rect.width / 2;
    const centerY = rect.top + rect.height / 2;
    
    for (let i = 0; i < 12; i++) {
        const particle = document.createElement('div');
        particle.style.position = 'fixed';
        particle.style.left = centerX + 'px';
        particle.style.top = centerY + 'px';
        particle.style.width = '8px';
        particle.style.height = '8px';
        particle.style.background = '#FFD700';
        particle.style.borderRadius = '50%';
        particle.style.boxShadow = '0 0 10px #FFD700';
        particle.style.pointerEvents = 'none';
        particle.style.zIndex = '9999';
        particle.style.willChange = 'transform, opacity';
        
        const angle = (i / 12) * Math.PI * 2;
        const velocity = 80 + Math.random() * 40;
        const tx = Math.cos(angle) * velocity;
        const ty = Math.sin(angle) * velocity;
        
        particle.animate([
            { transform: 'translate(-50%, -50%) scale(1)', opacity: 1 },
            { transform: `translate(calc(-50% + ${tx}px), calc(-50% + ${ty}px)) scale(0)`, opacity: 0 }
        ], {
            duration: 800,
            easing: 'ease-out'
        }).onfinish = () => particle.remove();
        
        document.body.appendChild(particle);
    }
}

function handleEnter(e, postId) {
    if (e.key === 'Enter') submitComment(postId);
}

function submitComment(postId) {
    const input = document.getElementById(`input-${postId}`);
    const text = input.value.trim();
    if (!text) return;
    
    const container = document.getElementById(`comments-${postId}`);
    const comment = document.createElement('div');
    comment.className = 'comment';
    comment.innerHTML = `
        <span class="comment-user" style="color: var(--gold);">You</span>
        <span class="comment-text">${text.replace(/</g, '&lt;')}</span>
        <span style="color: rgba(255,255,255,0.5); font-size: 0.75rem; margin-left: 0.5rem;">Just now</span>
    `;
    container.appendChild(comment);
    input.value = '';
    container.scrollTop = container.scrollHeight;
}

